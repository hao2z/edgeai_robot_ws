"""Build the circular MPPI comparison profile from the DWB robot baseline."""
from copy import deepcopy
import json
import math
from pathlib import Path
import sys
import yaml


def prepare(rectangle, mppi):
    result = deepcopy(rectangle)
    # Enclose the padded, axle-centred body; do not silently shrink the robot.
    local = rectangle['local_costmap']['local_costmap']['ros__parameters']
    padding = local.get('footprint_padding', 0.0)
    radius = math.ceil(max(math.hypot(x + math.copysign(padding, x),
                                     y + math.copysign(padding, y))
                           for x, y in json.loads(local['footprint'])) * 100) / 100
    for section in ('local_costmap', 'global_costmap'):
        costmap = result[section][section]['ros__parameters']
        costmap.pop('footprint', None)
        costmap.update(robot_radius=radius, footprint_padding=0.0)
        # Circular centre-cost collision checks need inflation to cover the radius.
        costmap['inflation_layer']['inflation_radius'] = max(
            costmap['inflation_layer']['inflation_radius'],
            math.ceil(radius / costmap['resolution']) * costmap['resolution'])
    result['controller_server']['ros__parameters']['controller_server.verbose'] = False
    follow = deepcopy(mppi['controller_server']['ros__parameters']['FollowPath'])
    # 80 x 50 ms = 4 s, at most 0.8 m at the robot's speed limit.
    # Keep the horizon inside the 3 m rolling costmap and model_dt at 20 Hz.
    follow.update(plugin='nav2_mppi_controller::MPPIController', motion_model='DiffDrive',
                  time_steps=80, model_dt=0.05, batch_size=1200, iteration_count=1,
                  vx_max=0.2, vx_min=-0.08, vy_max=0.0, wz_max=0.65,
                  ax_max=0.4, ax_min=-0.4, az_max=0.8,
                  # Low acceleration: per-step envelopes are 0.02 m/s and
                  # 0.04 rad/s. Avoid noise 6-8 times those achievable deltas.
                  vx_std=0.05, vy_std=0.0, wz_std=0.10,
                  prune_distance=1.2, transform_tolerance=0.2,
                  enforce_path_inversion=False, inversion_xy_tolerance=0.15,
                  inversion_yaw_tolerance=0.25, visualize=True,
                  regenerate_noises=True)
    # Publish only a small subset of candidates for the WSLg observer.
    follow['TrajectoryVisualizer'].update(trajectory_step=100, time_step=5)
    follow['CostCritic'].update(consider_footprint=False, trajectory_point_step=1,
                              near_goal_distance=0.5)
    follow['PathAlignCritic'].update(use_path_orientations=False)
    follow['PathAngleCritic'].update(mode=0)
    # A weak forward preference breaks symmetric stationary starts; reverse
    # remains available for local maneuvers; NavFn supplies geometric paths.
    follow['PreferForwardCritic'].update(enabled=True, cost_weight=2.0)
    follow['GoalCritic']['threshold_to_consider'] = 0.8
    follow['PathFollowCritic']['threshold_to_consider'] = 0.8
    result['controller_server']['ros__parameters']['FollowPath'] = follow
    return result


if __name__ == '__main__':
    rectangle, mppi, output = map(Path, sys.argv[1:])
    output.write_text('# MPPI circular comparison profile; generated by prepare_mppi_config.py.\n' +
        yaml.safe_dump(prepare(yaml.safe_load(rectangle.read_text()),
                               yaml.safe_load(mppi.read_text())), sort_keys=False),
        encoding='utf-8', newline='\n')
