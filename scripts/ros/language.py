@lru_cache(maxsize=1)
def _pattern():
    return re.compile('|'.join(re.escape(key) for key in sorted(TEXT, key=len, reverse=True)))


def language(value=None):
    value = value or os.environ.get('EDGEAI_LANGUAGE', 'zh')
    normalized = ALIASES.get(value.strip().lower())
    if normalized is None:
        raise ValueError(f'Unsupported language: {value}')
    return normalized


def localize(value, selected=None):
    if language(selected) == 'zh':
        return value
    # Single pass prevents translated text from being translated again. Compile
    # once per process: the 2 Hz diagnostics panel does not rebuild the catalog.
    return _pattern().sub(lambda match: TEXT[match[0]], value)


